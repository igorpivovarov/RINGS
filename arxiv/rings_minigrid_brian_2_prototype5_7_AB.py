@dataclass
class RingsParams:
    # Внутренние параметры SNN
    ring_size: int = 10
    snn_step_ms: int = 20
    w_ring: float = 7.6042
    w_input: float = 8.1468
    energy_low_threshold: float = 0.5722
    input_rate_hz: float = 175.3834
    sensor_range: int = 3

    @classmethod
    def from_json(cls, path: str) -> "RingsParams":
        if os.path.exists(path):
            with open(path, 'r') as f:
                data = json.load(f)
                valid_keys = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
                return cls(**valid_keys)
        return cls()

class Food(Ball):
    def __init__(self):
        super().__init__(color="green")
        self.is_food = True
        self.is_danger = False
    def can_overlap(self):
        return True

class Danger(Ball):
    def __init__(self):
        super().__init__(color="red")
        self.is_food = False
        self.is_danger = True
    def can_overlap(self):
        return True

class RingsHomeostasisEnv(MiniGridEnv):
    def __init__(self, size=9, sensor_range=3, wall_sensor_range=1):
        self.sensor_range = sensor_range
        self.wall_sensor_range = wall_sensor_range
        self.energy = 1.0
        view_size = 2 * sensor_range + 1
        super().__init__(mission_space=MissionSpace(mission_func=lambda: "survive"), grid_size=size, agent_view_size=view_size, render_mode="rgb_array")

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)
        self.energy = 1.0
        return self._get_obs(), {}

    def _gen_grid(self, width, height):
        self.grid = Grid(width, height)
        self.grid.wall_rect(0, 0, width, height)
        self.place_agent()
        for _ in range(3): self.place_obj(Food())
        for _ in range(2): self.place_obj(Danger())

    def gen_obs_grid(self, agent_view_size=None):
        grid, vis_mask = super().gen_obs_grid(agent_view_size)
        view_size = agent_view_size or self.agent_view_size
        center_x, center_y = view_size // 2, view_size - 1
        for i in range(view_size):
            for j in range(view_size):
                if abs(i - center_x) > self.sensor_range or abs(j - center_y) > self.sensor_range:
                    vis_mask[i, j] = False
        return grid, vis_mask

    def _get_obs(self):
        fwd = self.dir_vec; left = np.array([fwd[1], -fwd[0]]); right = -left
        def ray(d_vec, t):
            limit = self.wall_sensor_range if t == 'is_wall' else self.sensor_range
            for i in range(1, limit + 1):
                p = self.agent_pos + d_vec * i
                if not (0 <= p[0] < self.grid.width and 0 <= p[1] < self.grid.height): return (limit - i + 1) / limit if t == 'is_wall' else 0.0
                o = self.grid.get(*p)
                if t == 'is_wall' and (o is None or isinstance(o, Wall)):
                    if isinstance(o, Wall): return (limit - i + 1) / limit
                if o and getattr(o, t, False): return (limit - i + 1) / limit
            return 0.0
        return {"rstate": np.array([self.energy, ray(left, 'is_food'), ray(right, 'is_food'), ray(fwd, 'is_food'), ray(left, 'is_danger'), ray(right, 'is_danger'), ray(fwd, 'is_danger'), ray(left, 'is_wall'), ray(right, 'is_wall'), ray(fwd, 'is_wall')], dtype=np.float32), "pos": tuple(self.agent_pos)}

    def step(self, action):
        _, reward, term, trunc, info = super().step(action)
        self.energy -= 0.01
        cell = self.grid.get(*self.agent_pos)
        if cell and getattr(cell, 'is_food', False):
            self.energy = min(1.0, self.energy + 0.5); self.grid.set(*self.agent_pos, None); self.place_obj(Food())
        if self.energy <= 0: term = True
        return self._get_obs(), reward, term, trunc, {"energy": self.energy}

class RingsSNNController:
    def __init__(self, params: RingsParams):
        start_scope()
        self.params = params
        self.names = ["Explore", "EnergyLow", "FoodS", "Danger", "Escape", "ML", "MR", "MF"]
        self.rings = {n: (i*params.ring_size, (i+1)*params.ring_size) for i, n in enumerate(self.names)}
        self.G = NeuronGroup(len(self.names)*params.ring_size, "dv/dt=(-v-67*mV)/(15*ms) : volt (unless refractory)", threshold="v>-50*mV", reset="v=-65*mV", refractory=3*ms, method="exact")
        self.inputs = PoissonGroup(8, rates=0*Hz)
        self.S_in = Synapses(self.inputs, self.G, on_pre=f"v_post += {params.w_input}*mV")
        for i in range(8): self.S_in.connect(i=i, j=np.arange(i*params.ring_size, (i+1)*params.ring_size))
        self.S_ring = Synapses(self.G, self.G, on_pre=f"v_post += {params.w_ring}*mV")
        def link(src, dst): self.S_ring.connect(i=np.arange(*self.rings[src]), j=np.arange(*self.rings[dst]))
        link("Explore", "MF"); link("FoodS", "MF")
        self.spikes = SpikeMonitor(self.G)
        self.net = Network(self.inputs, self.G, self.S_in, self.S_ring, self.spikes)
        self.prev_counts = np.zeros(len(self.names) * params.ring_size)
        self.forward_streak = 0

    def step(self, obs):
        r = obs["rstate"]; self.inputs.rates = 0*Hz
        food_found = False
        if r[3] > 0.05: self.inputs.rates[7] = self.params.input_rate_hz * 5.0 * Hz; food_found = True
        elif r[1] > 0.05: self.inputs.rates[5] = self.params.input_rate_hz * 4.0 * Hz; food_found = True
        elif r[2] > 0.05: self.inputs.rates[6] = self.params.input_rate_hz * 4.0 * Hz; food_found = True

        wall_L, wall_R, wall_F = r[7], r[8], r[9]
        dngr_L, dngr_R, dngr_F = r[4], r[5], r[6]

        if self.forward_streak >= 4 and not food_found:
            if dngr_L < dngr_R and dngr_L < 0.1: self.inputs.rates[5] = self.params.input_rate_hz * 8.0 * Hz
            elif dngr_R < dngr_L and dngr_R < 0.1: self.inputs.rates[6] = self.params.input_rate_hz * 8.0 * Hz
            elif dngr_L < 0.1 and dngr_R < 0.1:
                if wall_L < wall_R: self.inputs.rates[5] = self.params.input_rate_hz * 8.0 * Hz
                else: self.inputs.rates[6] = self.params.input_rate_hz * 8.0 * Hz

        if wall_F > 0.5 and not food_found:
            if wall_L < wall_R: self.inputs.rates[5] = self.params.input_rate_hz * 6.0 * Hz
            else: self.inputs.rates[6] = self.params.input_rate_hz * 6.0 * Hz
        elif not food_found:
            self.inputs.rates[7] = self.params.input_rate_hz * 2.5 * Hz
            if r[0] > self.params.energy_low_threshold: self.inputs.rates[0] = self.params.input_rate_hz * 1.0 * Hz

        self.net.run(self.params.snn_step_ms * ms)
        current_counts = np.array(self.spikes.count)
        delta_spikes = current_counts - self.prev_counts
        self.prev_counts = current_counts

        acts = {n: np.sum(delta_spikes[s:e])/self.params.ring_size for n, (s, e) in self.rings.items()}
        m = [acts["ML"], acts["MR"], acts["MF"]]
        action = np.argmax(m)

        if action == 2: self.forward_streak += 1
        else: self.forward_streak = 0

        return action, acts

def main(num_steps=30, sensor_range=None):
    p = RingsParams()
    if sensor_range is not None:
        p.sensor_range = sensor_range
    else:
        sensor_range = p.sensor_range

    env = RingsHomeostasisEnv(sensor_range=sensor_range, wall_sensor_range=1); obs, _ = env.reset(seed=7)
    ctrl = RingsSNNController(p)
    action_names = {0: "← Left", 1: "→ Right", 2: "↑ Forward"}
    label_map = {"Explore": "EXPL", "EnergyLow": "ENRG", "FoodS": "FOOD", "Danger": "DNGR", "Escape": "ESCP", "ML": "L", "MR": "R", "MF": "F"}
    print(f"=== RINGS/TEVSER ̴2: Range={sensor_range}, Steps={num_steps} ===")
    for k in range(num_steps):
        a, acts = ctrl.step(obs); obs, _, term, _, info = env.step(a)
        r = obs["rstate"]
        streak_info = f" | Streak: {ctrl.forward_streak}" if ctrl.forward_streak > 0 else ""
        print(f"\nStep {k} | Action: {action_names[a]}{streak_info} | Wall(L/R/F): ({r[7]:.1f}, {r[8]:.1f}, {r[9]:.1f}) | Danger(L/R): ({r[4]:.1f}, {r[5]:.1f})")
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 3))
        ax1.imshow(env.render())
        short_labels = [label_map.get(l, l[:4]) for l in acts.keys()]
        ax2.bar(short_labels, acts.values(), color='lightgreen')
        plt.show(); plt.close(fig)
        if term: break

